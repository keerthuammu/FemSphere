import 'dart:typed_data';
import 'package:flutter_test/flutter_test.dart';
import 'package:femsphere/features/wearables/core/huami_aes.dart';

void main() {
  test('NIST FIPS-197 AES-128-ECB Test Vector', () {
    // Key: 2b7e1516 28aed2a6 abf71588 09cf4f3c
    final key = Uint8List.fromList([
      0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6,
      0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f, 0x3c,
    ]);

    // Plaintext: 6bc1bee2 2e409f96 e93d7e11 7393172a
    final pt = Uint8List.fromList([
      0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96,
      0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17, 0x2a,
    ]);

    // Expected NIST Ciphertext: 3ad77bb4 0d7a3660 a89ecaf3 2466ef97
    final expectedCt = [
      0x3a, 0xd7, 0x7b, 0xb4, 0x0d, 0x7a, 0x36, 0x60,
      0xa8, 0x9e, 0xca, 0xf3, 0x24, 0x66, 0xef, 0x97,
    ];

    final ct = HuamiAes.encryptBlock(pt, key);
    expect(ct, equals(expectedCt));
  });
}
